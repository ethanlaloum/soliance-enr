export const solarYieldClassBoundsKwhPerKwc = [1150, 1200, 1300, 1400];

const postalCodePattern = /^\d{5}$/;
const corsicaPostalPrefix = '20';
const upperCorsicaFirstPostalCode = 20200;

export const departmentCodeOfPostalCode = (postalCode: string): string | null => {
  const trimmed = postalCode.trim();
  if (!postalCodePattern.test(trimmed)) return null;
  const prefix = trimmed.slice(0, 2);
  if (prefix !== corsicaPostalPrefix) return prefix;
  return Number(trimmed) < upperCorsicaFirstPostalCode ? '2A' : '2B';
};

export const departmentSolarYieldOf = (
  postalCode: string,
  yields: DepartmentSolarYield[] = departmentSolarYields,
): DepartmentSolarYield | null => {
  const code = departmentCodeOfPostalCode(postalCode);
  return yields.find((department) => department.code === code) ?? null;
};

export const solarYieldClassOf = (yieldKwhPerKwc: number, bounds: number[] = solarYieldClassBoundsKwhPerKwc): number =>
  bounds.filter((bound) => yieldKwhPerKwc >= bound).length;

export const averageSolarYieldKwhPerKwc = (yields: DepartmentSolarYield[] = departmentSolarYields): number =>
  Math.round(yields.reduce((total, department) => total + department.yieldKwhPerKwc, 0) / yields.length);

export const solarYieldGapPercent = (yieldKwhPerKwc: number, yields: DepartmentSolarYield[] = departmentSolarYields): number =>
  Math.round((yieldKwhPerKwc / averageSolarYieldKwhPerKwc(yields) - 1) * 100);
